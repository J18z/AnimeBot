// ملاحظة آخر القائمة (للمالك وللادمن) — كل أمر فيه @ تقدر تكتب بدلها الاسم أو الرقم
const FINAL_NOTE = "> ملاحظة: في كل الأوامر اللي فيها @ تقدر تكتب الاسم المسجل أو رقمه في .تسجيلات (1 جوال، 1_خارجي) أو ترد على رسالة الشخص بالأمر، بدل المنشن.";

const SECTION_GLUE = `\n\n${SEP_LINE}\n`;

function renderSection(sec, texts, notes) {
  let out = `> *✠  ${sec.title}*\n\n${texts.join("\n")}`;
  for (const n of notes) out += `\n\n${n}`;
  return out;
}

// قسم المطور: كل شي
function buildOwnerMenu() {
  const parts = SECTIONS.map((sec) =>
    renderSection(
      sec,
      sec.entries.map((e) => e.text),
      (sec.notes || []).map((n) => n.text)
    )
  );
  return `${titleBlock("قـسـم الـ Owner", "👑")}\n${parts.join(SECTION_GLUE)}\n\n${FINAL_NOTE}\n\n${FOOT_WIDE.replace(/^ /, "")}`;
}

// قسم الادمن: بس الأوامر اللي بحزمته (allowed = Set مفاتيح الحزمة اللي يقدر يستخدمها هو)
// chatOnly: ادمن شات (أوامره تشتغل بشاته بس) — نضيف تنبيه بآخر القائمة
function buildAdminMenu(allowed, chatOnly = false) {
  const parts = [];
  for (const sec of SECTIONS) {
    const texts = [];
    for (const e of sec.entries) {
      if (e.keys === null) continue;
      if (e.keys === "staff") {
        texts.push(e.text);
        continue;
      }
      const hit = e.keys.filter((k) => allowed.has(k));
      if (!hit.length) continue;
      if (e.variants) hit.forEach((k) => texts.push(e.variants[k]));
      else texts.push(e.text);
    }
    if (!texts.length) continue;
    const notes = (sec.notes || []).filter((n) => n.who === "both").map((n) => n.text);
    parts.push(renderSection(sec, texts, notes));
  }
  let body = parts.length ? parts.join(SECTION_GLUE) : "> ما عندك أوامر بالحزمة حالياً.";
  const tail = [];
  if (parts.length) tail.push(FINAL_NOTE);
  if (chatOnly) tail.push("> أنت أدمن لهذا الشات فقط، أوامرك تشتغل هنا وما تشتغل بباقي القروبات.");
  return `${titleBlock("قـسـم الـ Admins", "🛡️")}\n${body}${tail.length ? `\n\n${tail.join("\n")}` : ""}\n\n${FOOT_WIDE.replace(/^ /, "")}`;
}

// ───────── .حزمة (للمالك) ─────────
// pkg: أوامر الحزمة، more: الممكن إضافتها، admins/immune/chatAdmins: نصوص جاهزة "اللقب ~ @المنشن"
function buildPackageText({ pkg, more, adminLines, immuneLines, chatInfo }) {
  const list = (arr) => (arr.length ? arr.map((x) => `- ${x}`).join("\n") : "- ما فيه");
  let out = `> 📦 حـزمـة الادمـن:\n${list(pkg.map((k) => "." + k))}`;
  out += `\n\n> الـمـمـكـن اضـافـتـهـا:\n${list(more.map((k) => "." + k))}`;
  out += `\n\n> 🔖 الادمـنـز: \n${list(adminLines)}`;
  out += `\n> 🛡️ عـلـيـهـم حـصـانـة:\n${list(immuneLines)}`;
  if (chatInfo) {
    out += `\n\n> 💬 هـذا الـشـات: ${chatInfo.locked ? "🔒 مـقـفـول" : "🔓 مـفـتـوح"}`;
    out += `\n> 👥 ادمـنـز هـذا الـشـات فـقـط:\n${list(chatInfo.adminLines)}`;
  }
  return out;
}

