// هل النص أمر بوت؟ (نقطة ملصوقة بكلمة أمر معروفة)
function isCommandText(text) {
  const m = /^\.([\u0600-\u06FF_]+)/.exec(String(text || ""));
  return !!m && COMMAND_WORDS.has(m[1]);
}

